// Re-run after adding/renaming victory clips; generated JS also works over file://.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const folder = path.join(root, 'assets/sounds/victory-announcements');
const sounds = {};
for (const file of fs.readdirSync(folder).sort()) {
  const match = file.match(/^(.+?) beats? (.+?) (BIGWIN|CLOSE) - .+\.mp3$/i);
  if (!match) continue;
  const winner = match[1].toLowerCase();
  // One supplied filename spells Boo as "book". Preserve the source filename.
  const loser = match[2].toLowerCase() === 'book' ? 'boo' : match[2].toLowerCase();
  const key = `${winner}|${loser}|${match[3].toUpperCase()}`;
  if (sounds[key]) throw new Error('Duplicate victory cue: ' + key);
  sounds[key] = file;
}
fs.writeFileSync(path.join(root, 'assets/sounds/victory-sounds.js'),
  '// Generated by _documents/codex-john-docs/sync-victory-sounds.cjs\nwindow.CandyVictorySounds = ' + JSON.stringify(sounds, null, 2) + ';\n');
console.log('Indexed ' + Object.keys(sounds).length + ' victory clips.');
